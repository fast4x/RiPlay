package it.fast4x.riplay.enums

/**
 * Trattamento dello sfondo dei widget della home screen.
 * Solid mantiene lo sfondo pieno (leggermente traslucido),
 * SemiTransparent lo attenua al 60%, Transparent lo rende
 * completamente trasparente lasciando vedere la wallpaper.
 */
enum class WidgetBackground {
    Solid,
    SemiTransparent,
    Transparent
}
